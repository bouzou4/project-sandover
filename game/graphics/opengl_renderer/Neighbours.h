#pragma once

#include <mutex>
#include <string>
#include <unordered_map>
#include <vector>

#include "common/common_types.h"
#include "common/math/Vector.h"

/*!
 * Neighbour fidelity (Jak 1 vista mode "neighbours"): every level adjacent to the levels the
 * game has loaded stays resident in the loader and is drawn by the vista renderer.
 */
namespace neighbours {

/// Outdoor levels adjacent to any of `loaded` (land seams and the village1 sea gaps), without
/// `loaded`.
std::vector<std::string> adjacent_to(const std::vector<std::string>& loaded);

/// Outdoor levels depicted by the stand-ins of `loaded` (kStandins), without `loaded` and `exclude`.
std::vector<std::string> standin_levels(const std::vector<std::string>& loaded,
                                        const std::vector<std::string>& exclude);

/// Level the player is in (pc-set-vista-viewer, from level-get-target-inside each frame).
void set_viewer(const std::string& level);
std::string viewer();

/// True if `level` may load and draw neighbours: kOutdoor, mirrored from
/// sandover/presets/vista.toml [outdoor]. Indoor levels (boss arenas, caves, citadel, sunken) draw
/// nothing beyond vanilla.
bool is_outdoor(const std::string& level);

/// True if neighbour `level` must not be drawn with the camera at `cam_m` (world metres):
/// kKeepOut, mirrored from sandover/presets/vista.toml [[keep_out]]. Its geometry stands inside
/// another level's play space, which vanilla never displays together with it.
bool kept_out(const std::string& level, const math::Vector3f& cam_m);

/// Set from gl_set_levels (game thread): the game's levels and the neighbours kept resident.
void set_resident(const std::vector<std::string>& game_levels,
                  const std::vector<std::string>& neighbour_levels);
/// Read on the render thread: the values of the last set_resident.
void get_resident(std::vector<std::string>* game_levels, std::vector<std::string>* neighbour_levels);

/// Viewer-level stand-in names to hide (vista_name_matches syntax) given the drawn neighbours.
std::string standin_filter(const std::vector<std::string>& viewer_levels,
                           const std::vector<std::string>& drawn_neighbours);

/// True if a merc model name is a med-res-level stand-in ("medres-<level>[N][-lodK]") of one of
/// `levels`.
bool is_medres_of(const char* model_name, const std::vector<std::string>& levels);

/*!
 * Palette weights of one level's own mood at a time of day, from the table built into gk
 * (NeighboursMood.inc, generated by sandover-mood-tables from mood-tables.gc). Mirrors
 * update-mood-palette / update-mood-quick and update-mood-itimes; effect slots (flames, lights,
 * lava) stay at zero.
 */
class MoodTable {
 public:
  /// Returns false if the level has no table (the caller keeps the viewer's weights).
  bool itimes_at(const std::string& level, float hour, math::Vector<s32, 4> out[4]);
  /// Hour (0-24) at which each palette slot has its largest weight (the middle of a plateau),
  /// -1 for slots never used. False for levels without a cycling table.
  bool slot_hours(const std::string& level, float out[8]);

 private:
  struct Entry {
    int s1 = 0, s2 = 0;
    float morph_start = 0, morph_end = 0;
  };
  struct Level {
    bool ok = false;
    int quick_slot = -1;
    std::vector<Entry> hours;
  };
  const Level& get(const std::string& level);
  std::unordered_map<std::string, Level> m_levels;
};

/// Pack 8 slot weights exactly as update-mood-itimes does (vftoi12, >> 6, ppach).
void pack_itimes(const float w[8], math::Vector<s32, 4> out[4]);

/// Largest per-slot difference between two itimes, in 1/64 units.
int itimes_diff(const math::Vector<s32, 4> a[4], const math::Vector<s32, 4> b[4]);

}  // namespace neighbours
