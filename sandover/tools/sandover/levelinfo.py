"""Facts from `goal_src/jak1/engine/level/level-info.gc` the engine needs as data.

`sandover-levelinfo --write-inc` regenerates `game/graphics/opengl_renderer/LevelSky.inc`
(level name and its `:sky` flag; the level heightfield is built only for sky levels).
"""

from __future__ import annotations

import argparse
from pathlib import Path

from .paths import root

LEVEL_INFO = Path("goal_src/jak1/engine/level/level-info.gc")
SKY_INC = Path("game/graphics/opengl_renderer/LevelSky.inc")


def level_skies(level_info: Path) -> dict[str, bool]:
    """Level name -> its `:sky` flag, in file order."""
    out, name = {}, None
    for line in level_info.read_text(encoding="utf-8").splitlines():
        t = line.strip()
        if t.startswith(":name '"):
            name = t.split("'", 1)[1].split()[0]
        elif t.startswith(":sky ") and name:
            out[name] = t.split()[1] == "#t"
            name = None
    return out


def sky_inc(skies: dict[str, bool]) -> str:
    lines = ["// generated by `sandover-levelinfo --write-inc` from level-info.gc; do not edit"]
    lines += [f'{{"{k}", {"true" if v else "false"}}},' for k, v in skies.items()]
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(prog="sandover-levelinfo", description=__doc__.split("\n")[0])
    ap.add_argument("--root", type=Path, default=root())
    ap.add_argument("--write-inc", action="store_true", help=f"write {SKY_INC}")
    a = ap.parse_args(argv)
    skies = level_skies(a.root / LEVEL_INFO)
    if a.write_inc:
        (a.root / SKY_INC).write_text(sky_inc(skies), encoding="utf-8", newline="\n")
    for k, v in skies.items():
        print(k, "sky" if v else "no sky")


if __name__ == "__main__":
    main()
