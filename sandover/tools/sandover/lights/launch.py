"""Write the engine's launch-light group table (`LaunchLights.inc`) from `entity_types.json`.

An entity type's ``launch`` entry names the particle groups whose launch means "this emitter is lit"
(``groups``) and where the light sits relative to the spawn origin, in the launcher's frame
(``offset_m``, or ``"bake"`` for the type's bake ``offset_m``). Only listed groups drive a light:
broken-state smoke, pickup streams and other groups of the same entity never do. The engine side is
`world_lights::launch_push` (WorldLights.h). Every group must be a ``defpartgroup`` in goal_src.

    uv run --no-sync python -m sandover.lights launch [--out FILE]
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from sandover import paths

CPP_TABLE_REL = "game/graphics/opengl_renderer/LaunchLights.inc"
TYPES_JSON = Path(__file__).with_name("entity_types.json")
INC_HEADER = [
    "// Generated by `sandover-lights launch` from sandover/tools/sandover/lights/entity_types.json",
    "// (`launch` entries). Do not edit; regenerate. See WorldLights.h launch_push.",
    "// Only these groups light their entity's row; the light sits at the spawn origin plus the",
    "// offset, rotated by the launcher's root quaternion (as vector-orient-by-quat!).",
    "// {group, x, y, z (m)}",
]


def launch_groups(types_json: Path = TYPES_JSON) -> dict[str, tuple[float, float, float]]:
    """Group name -> offset (m). A group listed by two types must have one offset."""
    types = json.loads(types_json.read_text(encoding="utf-8"))["types"]
    out: dict[str, tuple[float, float, float]] = {}
    for name, t in sorted(types.items()):
        la = t.get("launch")
        if not la:
            continue
        off = la.get("offset_m", [0.0, 0.0, 0.0])
        if off == "bake":
            off = t["bake"]["offset_m"]
        off = tuple(float(x) for x in off)
        for g in la["groups"]:
            if g in out and out[g] != off:
                raise ValueError(f"{g}: offset {off} ({name}) differs from {out[g]}")
            out[g] = off
    return dict(sorted(out.items()))


def defined_groups(goal_src: Path) -> set[str]:
    rx = re.compile(r"\(defpartgroup\s+([\w-]+)")
    names: set[str] = set()
    for p in goal_src.rglob("*.gc"):
        names.update(rx.findall(p.read_text(encoding="utf-8", errors="replace")))
    return names


def _f(v: float) -> str:
    t = f"{v:.3f}".rstrip("0")
    return t + "f" if not t.endswith(".") else t + "f"


def cpp_table(groups: dict[str, tuple[float, float, float]]) -> str:
    lines = list(INC_HEADER)
    for g, (x, y, z) in groups.items():
        lines.append(f'{{"{g}", {_f(x)}, {_f(y)}, {_f(z)}}},')
    return "\n".join(lines) + "\n"


def cpp_table_path() -> Path:
    return paths.root() / CPP_TABLE_REL


def write(out: Path | None = None) -> tuple[Path, dict]:
    groups = launch_groups()
    missing = sorted(set(groups) - defined_groups(paths.root() / "goal_src" / "jak1"))
    if missing:
        raise ValueError(f"not a defpartgroup in goal_src: {missing}")
    out = out or cpp_table_path()
    out.write_text(cpp_table(groups), encoding="utf-8", newline="\n")
    return out, groups
