"""Eco shots and blasts: the particle groups that carry a transient light.

A shot is a process whose type descends from ``projectile`` or ``arcing-shot`` (goal_src deftypes).
Its flight groups are the ``create-launch-control`` groups in the forms of that type (its
methods, behaviours and states); its blasts are the ``part-tracker-init`` groups spawned there,
the base types' included (``projectile-impact`` spawns the yellow fireball hit for every
projectile). Each group's colour, brightness and size come from its ``defpart`` data
(``particles.Group``). GOAL reports the group a live shot or blast is launching
(``pc-eco-light-push``, main.gc); the engine looks it up in ``EcoLights.inc``, written here
and committed like ``WorldLights.inc``.

``projectile-blue`` is left out: it is the blue eco stream flying into Jak when he picks the eco
up (``spawn-projectile-blue``), a pickup effect that hits nothing, not a shot.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

from sandover import paths
from sandover.lights import particles as P

SHOT_BASES = ("projectile", "arcing-shot")
NOT_SHOTS = ("projectile-blue",)
CPP_TABLE_REL = "game/graphics/opengl_renderer/EcoLights.inc"
INC_HEADER = ("// generated by `sandover-lights eco` from goal_src (sandover/lights/eco.py); do not edit",
              "// {group, kind (0 shot in flight, 1 blast), r, g, b, bounds radius_m}")

_DEFTYPE = re.compile(r"^\(deftype\s+(\S+)\s+\((\S+)\)", re.M)
_LAUNCH = re.compile(r"create-launch-control\s+(group-[\w-]+)")
_TRACKER = re.compile(r"part-tracker-init\s+(group-[\w-]+)")


def shot_colour(g: P.Group) -> list[float] | None:
    """Alpha-weighted mean colour of the group's textured parts, max channel 1. Shot groups draw
    their colour with plain and additive sprites alike (the bit3 flag the census reads is on the
    white cores only), so every lit part counts; black and water-ring parts do not."""
    ps = [p for p in g.parts if p.texture and not p.texture.startswith(P.NOT_LIGHT_TEXTURES)
          and max(p.rgba.get(c, 0.0) for c in "rgb") >= 16.0]
    if not ps:
        return None
    w = [max(p.rgba.get("a", 128.0), 1.0) for p in ps]
    c = [sum(p.rgba.get(ch, 0.0) * wi for p, wi in zip(ps, w)) / sum(w) for ch in "rgb"]
    m = max(c)
    return [round(v / m, 3) for v in c] if m > 0 else None


@dataclass
class EcoGroup:
    name: str
    kind: int  # 0 flight, 1 blast
    owner: str  # shot type
    colour: list[float]
    radius_m: float  # the group's bounding sphere
    source: str


def _owner_forms(text: str, t: str) -> list[str]:
    """Top-level forms of ``text`` that belong to type ``t``."""
    pats = [rf"\(defmethod\s+\S+\s+\(\(\w+\s+{re.escape(t)}\)",
            rf"\(defbehavior\s+\S+\s+{re.escape(t)}\s",
            rf"\(defstate\s+\S+\s+\({re.escape(t)}\)"]
    out = []
    for pat in pats:
        for _, form, _ in P._forms(text, re.compile("^" + pat, re.M)):
            out.append(form)
    return out


def shot_types(goal_src: Path) -> tuple[dict[str, str], dict[str, list[str]]]:
    """{shot type: parent} and {type: texts of the files that name it} for every type descending
    from SHOT_BASES."""
    parent: dict[str, str] = {}
    files: list[str] = []
    for f in sorted(goal_src.rglob("*.gc")):
        if "old" in f.relative_to(goal_src).parts:
            continue
        text = f.read_text(encoding="utf-8", errors="ignore")
        files.append(text)
        for m in _DEFTYPE.finditer(text):
            parent.setdefault(m.group(1), m.group(2))

    def is_shot(t: str) -> bool:
        seen = 0
        while t in parent and seen < 32:
            if t in SHOT_BASES:
                return True
            t, seen = parent[t], seen + 1
        return t in SHOT_BASES

    shots = {t: p for t, p in parent.items() if is_shot(t) and t not in NOT_SHOTS}
    shots.update({b: parent.get(b, "") for b in SHOT_BASES})
    return shots, {t: [x for x in files if t in x] for t in shots}


def eco_groups(goal_src: Path | None = None) -> list[EcoGroup]:
    goal_src = goal_src or paths.root() / "goal_src/jak1"
    groups = P.load_groups(goal_src)
    shots, texts = shot_types(goal_src)
    found: dict[str, EcoGroup] = {}
    for t in sorted(set(shots) - set(SHOT_BASES)):
        chain, cur = [], t
        while cur in shots and cur:
            chain.append(cur)
            cur = shots[cur]
        for kind, rx in ((0, _LAUNCH), (1, _TRACKER)):
            names: dict[str, str] = {}
            # flight groups are the type's own; blasts are inherited from the base shot types
            for owner in chain if kind == 1 else chain[:1]:
                for text in texts[owner]:
                    for form in _owner_forms(text, owner):
                        for n in rx.findall(form):
                            names.setdefault(n, owner)
            for n, owner in names.items():
                g = groups.get(n)
                c = shot_colour(g) if g else None
                if not g or not c or n in found:
                    continue
                found[n] = EcoGroup(n, kind, owner, c, g.radius_m, g.source)
    return sorted(found.values(), key=lambda e: e.name)


def _f(v: float) -> str:
    t = f"{v:.3f}".rstrip("0")
    return t + "f" if not t.endswith(".") else t + "f"


def cpp_table(rows: list[EcoGroup]) -> str:
    lines = list(INC_HEADER)
    for e in rows:
        r, g, b = e.colour
        lines.append(f'{{"{e.name}", {e.kind}, {_f(r)}, {_f(g)}, {_f(b)}, '
                     f'{_f(e.radius_m)}}},  // {e.owner}, {e.source}')
    return "\n".join(lines) + "\n"


def cpp_table_path() -> Path:
    return paths.root() / CPP_TABLE_REL


def write(out: Path | None = None) -> tuple[Path, list[EcoGroup]]:
    rows = eco_groups()
    out = out or cpp_table_path()
    out.write_text(cpp_table(rows), encoding="utf-8", newline="\n")
    return out, rows
