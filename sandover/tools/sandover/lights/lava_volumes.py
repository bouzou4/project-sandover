"""Generate the engine's lava volume table (``LavaVolumes.inc``) from game data.

Nothing here is typed by hand:

- **Which types.** Every ``water-vol-method-22`` in ``goal_src/jak1/levels`` that sets
  ``(water-flag lava)`` names a lava ``water-anim`` type (ogre-lava, villagec-lava, lavatube-lava).
- **Per entity** (``decompiler_out/jak1/entities/<level>-actors.json``): actor id, name, the
  ``vol`` planes (the footprint: the planes whose normal is along x or z) and ``water-height``
  (the surface, absolute, as ``water-vol`` ``init!`` reads it).

Usage::

    uv run --no-sync python -m sandover.lights.lava_volumes [--check]

Writes ``game/graphics/opengl_renderer/LavaVolumes.inc`` in this checkout (``--check`` only
compares). Decompiler output is read from the primary checkout when this one has none.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path

from sandover import paths

METER = 4096.0
INC_REL = "game/graphics/opengl_renderer/LavaVolumes.inc"
METHOD = re.compile(r"\(defmethod water-vol-method-22 \(\(this ([\w-]+)\)\)(.*?)\n\(", re.S)


def checkout() -> Path:
    return paths.root()


def decompiler_out() -> Path:
    """``decompiler_out/jak1`` of this checkout, else of the primary checkout."""
    for base in (paths.root(), paths.data_dir().parents[1]):
        d = base / "decompiler_out" / "jak1"
        if (d / "entities").is_dir():
            return d
    raise FileNotFoundError("no decompiler_out/jak1 in this checkout or the primary one")


def lava_types(goal_levels: Path) -> set[str]:
    out = set()
    for f in sorted(goal_levels.rglob("*.gc")):
        for m in METHOD.finditer(f.read_text(encoding="utf-8") + "\n("):
            if "(water-flag lava)" in m.group(2) and "logior!" in m.group(2):
                out.add(m.group(1))
    return out


@dataclass
class Volume:
    level: str
    aid: int
    name: str
    x0: float
    x1: float
    z0: float
    z1: float
    surface_m: float


def footprint(planes: list[list[float]]) -> tuple[float, float, float, float]:
    """xz box of a ``vol`` (inside where n . p <= d), metres."""
    x0 = z0 = -1e9
    x1 = z1 = 1e9
    for nx, ny, nz, d in planes:
        if abs(ny) > 0.999:
            continue
        if abs(nx) > 0.999 and abs(nz) < 1e-3:
            if nx > 0:
                x1 = min(x1, d / METER)
            else:
                x0 = max(x0, -d / METER)
        elif abs(nz) > 0.999 and abs(nx) < 1e-3:
            if nz > 0:
                z1 = min(z1, d / METER)
            else:
                z0 = max(z0, -d / METER)
        else:
            raise ValueError(f"vol plane not axis-aligned: {nx} {ny} {nz}")
    return x0, x1, z0, z1


def volumes(dout: Path, types: set[str]) -> list[Volume]:
    out = []
    for f in sorted((dout / "entities").glob("*-actors.json")):
        level = f.name[: -len("-actors.json")]
        for a in json.loads(f.read_text(encoding="utf-8")) or []:
            if a.get("etype") not in types:
                continue
            lump = a["lump"]
            x0, x1, z0, z1 = footprint(lump["vol"])
            out.append(Volume(level, int(a["aid"]), lump.get("name", a["etype"]), x0, x1, z0, z1,
                              lump["water-height"][0] / METER))
    return out


def render(vols: list[Volume]) -> str:
    lines = ["// Generated by sandover.lights.lava_volumes from the decompiled game; do not edit.",
             "// {level, aid, name, x0, x1, z0, z1 (footprint, m), surface (m)}"]
    for v in vols:
        lines.append(f'{{"{v.level}", {v.aid}, "{v.name}", {v.x0:.3f}f, {v.x1:.3f}f, {v.z0:.3f}f, '
                     f"{v.z1:.3f}f, {v.surface_m:.3f}f}},")
    return "\n".join(lines) + "\n"


def generate() -> str:
    types = lava_types(checkout() / "goal_src" / "jak1" / "levels")
    return render(volumes(decompiler_out(), types))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="lava_volumes", description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, default=checkout() / INC_REL)
    ap.add_argument("--check", action="store_true", help="compare with --out, write nothing")
    args = ap.parse_args(argv)
    text = generate()
    if args.check:
        same = args.out.exists() and args.out.read_text(encoding="utf-8") == text
        print("up to date" if same else f"{args.out} differs from the game data")
        return 0 if same else 1
    args.out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {args.out} ({text.count(chr(10)) - 2} volumes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
